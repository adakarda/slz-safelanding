def box(name, cx, cy, cz, sx, sy, sz, label, rgb):
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} {cz:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{rgb[0]}</ambient><diffuse>{rgb[1]}</diffuse></material></visual>
      </link>
      <plugin filename="gz-sim-label-system" name="gz::sim::systems::Label"><label>{label}</label></plugin>
    </model>
"""


def disc(name, cx, cy, cz, r, sz, label, rgb):
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} {cz:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><cylinder><radius>{r:.3f}</radius><length>{sz:.3f}</length></cylinder></geometry></collision>
        <visual name="visual"><geometry><cylinder><radius>{r:.3f}</radius><length>{sz:.3f}</length></cylinder></geometry>
          <material><ambient>{rgb[0]}</ambient><diffuse>{rgb[1]}</diffuse></material></visual>
      </link>
      <plugin filename="gz-sim-label-system" name="gz::sim::systems::Label"><label>{label}</label></plugin>
    </model>
"""


def rect_area(rects):
    return sum(abs(x1 - x0) * abs(y1 - y0) for x0, y0, x1, y1 in rects)


# ------------------------------------------------------------------ islands
def island(kind, cx, cy, **k):
    """Island description: rectangles/discs in world coordinates, top height,
    landable area, and the models that draw it."""
    z = k.get('taban', 0.0)
    top = z + SLAB
    models, rects, discs = [], [], []
    holes = []
    if kind == 'kare':
        sx, sy = k['sx'], k['sy']
        rects = [[cx - sx / 2, cy - sy / 2, cx + sx / 2, cy + sy / 2]]
    elif kind == 'L':
        s, w = k['s'], k['kol']
        x0, y0 = cx - s / 2, cy - s / 2
        rects = [[x0, y0, x0 + s, y0 + w],            # bottom arm, full width
                 [x0, y0 + w, x0 + w, y0 + s]]        # left arm, above it
    elif kind == 'daire':
        discs = [[cx, cy, k['d'] / 2]]
    for i, (x0, y0, x1, y1) in enumerate(rects):
        models.append(box(f'ada_{i}', (x0 + x1) / 2, (y0 + y1) / 2, z + SLAB / 2,
                          x1 - x0, y1 - y0, SLAB, LABEL['grass'], GRASS_RGB))
    for i, (x, y, r) in enumerate(discs):
        models.append(disc(f'ada_d{i}', x, y, z + SLAB / 2, r, SLAB,
                           LABEL['grass'], GRASS_RGB))
    area = rect_area(rects) + sum(math.pi * r * r for _, _, r in discs)
    if k.get('engel'):
        e = k['engel']
        h = 0.5
        models.append(box('engel', cx, cy, top + h / 2, e, e, h, LABEL['terrain'], TERRAIN_RGB))
        holes = [[cx - e / 2, cy - e / 2, cx + e / 2, cy + e / 2]]
        area -= e * e
    return {
        'models': models,
        'yuzey': {'ad': 'ada', 'z': round(top, 3), 'inilebilir': True,
                  'sekil': kind, 'merkez': [round(cx, 3), round(cy, 3)],
                  'dikdortgenler': [[round(v, 3) for v in r] for r in rects],
                  'daireler': [[round(v, 3) for v in d] for d in discs],
                  'alan_m2': round(area, 3)},
        'engel': ({'ad': 'engel', 'z': round(top + 0.5, 3), 'inilebilir': False,
                   'dikdortgenler': holes} if holes else None),
    }


def start_conditions(rng, center, off_range):
    r = rng.uniform(*off_range)
    a = rng.uniform(0.0, 2.0 * math.pi)
    return {
        'irtifa_m': round(rng.uniform(10.0, 20.0), 1),
        'ofset_m': round(r, 2),
        'ofset_aci_deg': round(math.degrees(a), 1),
        'dogus': [round(center[0] + r * math.cos(a), 2),
                  round(center[1] + r * math.sin(a), 2), 0.0, 0.0, 0.0,
                  round(rng.uniform(-math.pi, math.pi), 3)],
    }


def people(rng, n, center, params, name_prefix='veri_kisi'):
    """n people walking straight lines that pass within 5 m of the island."""
    mobs, blocks = [], []
    for i in range(n):
        a = rng.uniform(0.0, math.pi)
        px = center[0] + rng.uniform(-5, 5)
        py = center[1] + rng.uniform(-5, 5)
        half = 15.0
        start = [round(px - half * math.cos(a), 2), round(py - half * math.sin(a), 2)]
        goal = [round(px + half * math.cos(a), 2), round(py + half * math.sin(a), 2)]
        name = f'{name_prefix}_{i}'
        mobs.append({'kind': 'person', 'name': name, 'start': start, 'goal': goal,
                     'speed': round(rng.uniform(0.8, 1.4), 2), 'z': 0.9})
        blocks.append(gen_world.person_model_block(params, name, start))
    return mobs, blocks


def wind_block(v, yon_deg, olcek):
    if v <= 0:
        return '', ''
    vx = v * math.cos(math.radians(yon_deg))
    vy = v * math.sin(math.radians(yon_deg))
    plugins = PX4_PLUGINS + f"""    <plugin filename="gz-sim-wind-effects-system" name="gz::sim::systems::WindEffects">
      <force_approximation_scaling_factor>{olcek}</force_approximation_scaling_factor>
    </plugin>
"""
    return plugins, f"""    <wind>
      <linear_velocity>{vx:.3f} {vy:.3f} 0</linear_velocity>
    </wind>"""


def write_world(name, desc, isl, extra_models, start, outdir, mobs=None,
                ruzgar=(0.0, 0.0, 1.0), platform=None):
    plugins, wind = wind_block(*ruzgar)
    parts = [HEADER.format(aciklama=desc, ad=name, eklentiler=plugins,
                           t_amb=TERRAIN_RGB[0], t_dif=TERRAIN_RGB[1],
                           zemin_label=LABEL['terrain'])]
    parts += extra_models + isl['models']
    parts.append(FOOTER.format(ruzgar=wind))
    os.makedirs(outdir, exist_ok=True)
    sdf = os.path.join(outdir, f'{name}.sdf')
    with open(sdf, 'w') as f:
        f.write(''.join(parts))
    yuzeyler = [isl['yuzey']]
    if isl['engel']:
        yuzeyler.append(isl['engel'])
    if platform:
        yuzeyler.append(platform)
    meta = {
        'dunya_id': name, 'gz_world': name, 'aciklama': desc,
        'zemin_z': 0.0, 'zemin_sinifi': 2, 'hedef': 'ada',
        'yuzeyler': yuzeyler, 'baslangic': start,
        'ruzgar': {'hiz_mps': ruzgar[0], 'yon_deg': ruzgar[1], 'olcek': ruzgar[2]},
        'hareketli_kisi': len(mobs or []),
    }
    if mobs is not None:
        layout = os.path.join(outdir, f'{name}.mobs.yaml')
        with open(layout, 'w') as f:
            yaml.safe_dump({'seed': None, 'mobs': mobs}, f, sort_keys=False)
        meta['mob_layout_file'] = layout
    with open(os.path.join(outdir, f'{name}.yaml'), 'w') as f:
        yaml.safe_dump(meta, f, sort_keys=False, allow_unicode=True)
    return sdf


def suffix(ruzgar):
    return f'_r{ruzgar[0]:g}'.replace('.', 'p') if ruzgar[0] > 0 else ''


def sabit(ruzgar, outdir):
    """W1-W8 from the task, island centre at the world origin."""
    defs = {
        'w1': ('4x4 m kare ada', dict(kind='kare', sx=4, sy=4)),
        'w2': ('6x6 m kare ada', dict(kind='kare', sx=6, sy=6)),
        'w3': ('10x10 m kare ada', dict(kind='kare', sx=10, sy=10)),
        'w4': ('20x20 m kare ada', dict(kind='kare', sx=20, sy=20)),
        'w5': ('10x10 m, zeminden 4 m yuksek platform', dict(kind='kare', sx=10, sy=10, taban=4.0)),
        'w6': ('10x10 m L sekli, kollar 6 m', dict(kind='L', s=10, kol=6)),
        'w7': ('10 m capli daire ada', dict(kind='daire', d=10)),
        'w8': ('10x10 m kare ada, ortasinda 2x2 m inilemez nesne', dict(kind='kare', sx=10, sy=10, engel=2.0)),
    }
    made = []
    for key, (desc, spec) in defs.items():
        rng = random.Random(f'sabit-{key}')
        kind = spec.pop('kind')
        isl = island(kind, 0.0, 0.0, **spec)
        extra, platform = [], None
        off = (0.0, 4.0)
        if spec.get('taban'):
            # The platform body: terrain class (not landable, not a hazard),
            # grass slab on top. Spawn off the platform so the EKF origin is
            # on the ground and the 4 m offset is what gets measured.
            extra.append(box('platform', 0.0, 0.0, 2.0, 10.0, 10.0, 4.0,
                             LABEL['terrain'], TERRAIN_RGB))
            platform = {'ad': 'platform', 'z': 4.0, 'inilebilir': False,
                        'dikdortgenler': [[-5.0, -5.0, 5.0, 5.0]]}
            off = (6.5, 8.0)
        start = start_conditions(rng, (0.0, 0.0), off)
        name = f'veri_{key}{suffix(ruzgar)}'
        made.append(write_world(name, desc, isl, extra, start, outdir,
                                mobs=[], ruzgar=ruzgar, platform=platform))
    return made


def rastgele(seed, ruzgar, outdir, params):
    rng = random.Random(seed)
    kind = rng.choice(['kare', 'L', 'daire'])
    cx, cy = round(rng.uniform(-8, 8), 2), round(rng.uniform(-8, 8), 2)
    if kind == 'kare':
        sx = rng.uniform(3, 20)
        sy = min(20.0, max(3.0, sx * rng.uniform(0.5, 2.0)))
        isl = island('kare', cx, cy, sx=round(sx, 2), sy=round(sy, 2))
        desc = f'rastgele kare ada {sx:.1f}x{sy:.1f} m'
    elif kind == 'L':
        s = rng.uniform(8, 20)
        kol = s * rng.uniform(0.4, 0.6)
        isl = island('L', cx, cy, s=round(s, 2), kol=round(kol, 2))
        desc = f'rastgele L ada {s:.1f} m, kol {kol:.1f} m'
    else:
        d = rng.uniform(3, 20)
        isl = island('daire', cx, cy, d=round(d, 2))
        desc = f'rastgele daire ada d={d:.1f} m'
    n = rng.randint(0, 2)
    mobs, blocks = people(rng, n, (cx, cy), params)
    start = start_conditions(rng, (cx, cy), (0.0, 4.0))
    name = f'veri_ada_t{seed}{suffix(ruzgar)}'
    return write_world(name, desc + f', {n} hareketli kisi', isl, blocks, start,
                       outdir, mobs=mobs, ruzgar=ruzgar)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('kip', choices=['sabit', 'rastgele'])
    p.add_argument('--tohum-bas', type=int, default=2001)
    p.add_argument('--sayi', type=int, default=30)
    p.add_argument('--ruzgar', type=float, default=0.0, help='m/s, 0 = yok')
    p.add_argument('--ruzgar-yon', type=float, default=45.0, help='derece, ENU, x eksenden')
    p.add_argument('--ruzgar-olcek', type=float, default=1.0,
                   help='WindEffects force_approximation_scaling_factor')
    p.add_argument('--cikti', default=None)
    a = p.parse_args()
    ruzgar = (a.ruzgar, a.ruzgar_yon, a.ruzgar_olcek)
    params = gen_world.load_params()
    if a.kip == 'sabit':
        made = sabit(ruzgar, a.cikti or SABIT_DIR)
    else:
        made = [rastgele(a.tohum_bas + i, ruzgar, a.cikti or RASTGELE_DIR, params)
                for i in range(a.sayi)]
    for m in made:
        print(m)


if __name__ == '__main__':
    main()
