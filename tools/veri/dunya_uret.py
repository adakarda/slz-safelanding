#!/usr/bin/env python3
"""Island worlds for the data-collection task (Asama 2). New files only.

    tools/veri/dunya_uret.py sabit [--ruzgar V --ruzgar-yon DEG]
    tools/veri/dunya_uret.py rastgele --tohum-bas 2001 --sayi 30 [--ruzgar V]

Every world is a field of grass islands in non-landable ground. The ground is
TERRAIN_HAZARD (class 2): not landable, but not a hazard class either, so a
site owes it only the 2 m class-seam margin, not the 3 m SORA separation that
water or structure would demand (decided 2026-10-03; with water, islands under
~6 m could never produce a candidate).

Each world gets a yaml next to it with the ground truth the recorder needs:
surface heights, the target island's area/centre/shape, the start conditions
drawn from the seed, the wind, and the moving people. tools/veri/dunya.py
reads it.

Fixed worlds (sabit) go to src/eland_sim/worlds/veri/, random ones to
~/eland_veri/dunyalar/. A world named NAME is NAME.sdf and its gz world is
also called NAME, because PX4 opens <worlds>/$PX4_GZ_WORLD.sdf.

Geometry notes, measured against the detector's own rules (r_fit 1 m,
r_class_edge 2 m on a 0.2 m grid):
  * an island narrower than ~4.4 m has no cell 2 m from its seam, so W1
    (4x4) and random islands under ~4.4 m produce no candidate -- kept as
    "no site" examples, the mode then times out and descends blind;
  * W6's L arms are 6 m wide for the same reason (4 m arms are unselectable);
  * W8's centre obstacle is also non-hazard class, otherwise the 3 m SORA
    separation from it and the 2 m seam margin leave nothing on a 10x10 m
    island.
"""
